    public static String get(String signal) {
        if (signal == null || signal.trim().isEmpty()) return "";

        // ✨ startsWith 대신 contains를 사용하여
        // "RSI 25.1 — 극단적 과매도" 처럼 동적 수치가 들어와도 '극단적 과매도' 키워드를 정확히 잡아냅니다.
        return DESC.entrySet().stream()
                .filter(e -> signal.contains(e.getKey()))
                .map(Map.Entry::getValue)
                .findFirst()
                .orElse("현재 설정된 조건에 매칭되는 상세 해설이 없습니다. (혹은 데이터 수집 중입니다.)");
    }
