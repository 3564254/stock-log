    public static String get(String signal) {
        if (signal == null) return "";
        return DESC.entrySet().stream()
                .filter(e -> signal.trim().startsWith(e.getKey()))
                .map(Map.Entry::getValue)
                .findFirst()
                .orElse("");
    }
